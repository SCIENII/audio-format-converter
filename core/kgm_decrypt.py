def _decrypt_kgm_core(data, key_table):
    """
    核心解密算法：使用密钥表对数据进行 XOR 解密
    
    Kugou 的算法：result[i] = data[i] ^ key_table[(i + key_table[i % 256]) % 256]
    """
    result = bytearray(len(data))
    for i in range(len(data)):
        idx = (i + key_table[i % 256]) % 256
        result[i] = data[i] ^ key_table[idx]
    return bytes(result)


def detect_audio_format(audio_data):
    """检测解密后的音频格式"""
    if audio_data[:4] == b"fLaC":
        return "flac"
    if audio_data[:3] == b"\xff\xfb" or audio_data[:2] == b"\xff\xf3" or audio_data[:2] == b"\xff\xf2":
        return "mp3"
    if audio_data[:4] == b"RIFF":
        return "wav"
    if audio_data[:4] == b"OggS":
        return "ogg"
    if audio_data[:4] == b"\x00\x00\x00\x20" and audio_data[4:8] == b"ftyp":
        return "m4a"
    if audio_data[:4] == b".snd":
        return "au"
    # 默认查看前两个字节判断
    if audio_data[0] == 0xff and (audio_data[1] & 0xe0) == 0xe0:
        return "mp3"
    return "mp3"  # 默认mp3


def parse_kgm(filepath):
    """
    解析并解密 KGM 文件
    
    KGM 文件结构:
      [0:4]   Magic: "KGM " (0x4B474D20) 或变种
      [4:8]   Header size (uint32 LE)
      [8:12]  Audio data offset (uint32 LE)
      [12:...] 其他头部信息
      [audio_offset:] 加密的音频数据
    
    返回: (decrypted_audio_data, format_string, info_dict)
    """
    with open(filepath, "rb") as f:
        data = f.read()
    
    if len(data) < 16:
        raise ValueError("文件太小，不是有效的 KGM 文件")
    
    # 读取音频数据偏移量
    # KGM 的音频数据通常在偏移 0x400 (1024) 或更靠后
    # 不同版本的 KGM 有不同的头部结构
    
    # 简单策略：跳过前 1024 字节（标准 KGM 头部）
    # 如果文件有明确的偏移量指示，则使用它
    audio_offset = 0x400  # 默认 1024 字节头部
    
    if len(data) >= 12:
        # 尝试读取偏移量
        possible_offset = struct.unpack_from("<I", data, 8)[0]
        if 0x100 <= possible_offset <= len(data) - 16:
            audio_offset = possible_offset
    
    # 提取并解密音频数据
    encrypted_audio = data[audio_offset:]
    
    # 对前 4 字节用更复杂的方式检测
    # 尝试不同的偏移量
    for test_offset in [0x400, 0x800, 0xC00, 0x1000]:
        if test_offset < len(data) and test_offset != audio_offset:
            test_data = data[test_offset:test_offset+4]
            # 尝试在这些偏移量解密
            test_decrypted = _decrypt_kgm_core(test_data, _KGM_KEY_TABLE)
            if test_decrypted[:4] == b"fLaC" or test_decrypted[:2] == b"\xff\xfb":
                audio_offset = test_offset
                encrypted_audio = data[audio_offset:]
                break
    
    decrypted_audio = _decrypt_kgm_core(encrypted_audio, _KGM_KEY_TABLE)
    
    # 检测格式
    fmt = detect_audio_format(decrypted_audio)
    
    info = {
        "format": "kgm",
        "original_ext": "kgm",
    }
    
    return decrypted_audio, fmt, info


def parse_mgg(filepath):
    """
    解析并解密 MGG 文件（新版格式）
    
    MGG 文件结构类似 KGM，但使用不同的密钥表
    
    返回: (decrypted_audio_data, format_string, info_dict)
    """
    with open(filepath, "rb") as f:
        data = f.read()
    
    if len(data) < 16:
        raise ValueError("文件太小，不是有效的 MGG 文件")
    
    # MGG 的头部结构和偏移量分析
    audio_offset = 0x400  # 默认
    
    if len(data) >= 12:
        possible_offset = struct.unpack_from("<I", data, 8)[0]
        if 0x100 <= possible_offset <= len(data) - 16:
            audio_offset = possible_offset
    
    # 尝试检测音频起始位置
    # MGG 的头部可能包含 Fe 开头的魔数
    for test_offset in [0x400, 0x800, 0xC00, 0x1000, 0x2000]:
        if test_offset < len(data) and test_offset != audio_offset:
            test_data = data[test_offset:test_offset+4]
            test_decrypted = _decrypt_kgm_core(test_data, _MGG_KEY_TABLE)
            if test_decrypted[:4] == b"fLaC" or test_decrypted[:2] == b"\xff\xfb":
                audio_offset = test_offset
                break
    
    encrypted_audio = data[audio_offset:]
    decrypted_audio = _decrypt_kgm_core(encrypted_audio, _MGG_KEY_TABLE)
    
    # 检测格式
    fmt = detect_audio_format(decrypted_audio)
    
    info = {
        "format": "mgg",
        "original_ext": "mgg",
    }
    
    return decrypted_audio, fmt, info


def decrypt_kgm_mgg(filepath):
    """
    自动检测 KGM/MGG 并解密
    
    返回: (decrypted_audio, fmt_str, info_dict)
    """
    ext = os.path.splitext(filepath)[1].lower()
    
    if ext == ".kgm":
        return parse_kgm(filepath)
    elif ext == ".mgg":
        return parse_mgg(filepath)
    else:
        # 自动检测
        with open(filepath, "rb") as f:
            header = f.read(16)
        
        if header[:4] == b"KGM " or header[:3] == b"KGM":
            return parse_kgm(filepath)
        elif header[:3] == b"MGG":
            return parse_mgg(filepath)
        else:
            # 默认尝试 KGM
            return parse_kgm(filepath)


